function wall(
  x1: number,
  y1: number,
  x2: number,
  y2: number,
  color = BOUNDARY,
  height = 1.25,
  material: WallMaterial = "plaster",
  thickness = 0.09,
): WallSegment {
  return {
    start: { x: x1, y: y1 },
    end: { x: x2, y: y2 },
    color,
    height,
    material,
    thickness,
  };
}

function rectangle(
  x1: number,
  y1: number,
  x2: number,
  y2: number,
  color = OBSTACLE,
  height = 0.9,
  material: WallMaterial = "plaster",
): WallSegment[] {
  return [
    wall(x1, y1, x2, y1, color, height, material),
    wall(x2, y1, x2, y2, color, height, material),
    wall(x2, y2, x1, y2, color, height, material),
    wall(x1, y2, x1, y1, color, height, material),
  ];
}

function floorZone(
  id: string,
  label: string,
  x1: number,
  y1: number,
  x2: number,
  y2: number,
  color: number,
  pattern: SurfacePattern = "wood",
  accentColor?: number,
  patternScale = 1,
  patternRotation = 0,
): FloorZone {
  return {
    id,
    label,
    min: { x: x1, y: y1 },
    max: { x: x2, y: y2 },
    color,
    pattern,
    accentColor,
    patternScale,
    patternRotation,
  };
}

function furnishing(
  id: string,
  kind: WorldObjectKind,
  x: number,
  y: number,
  width: number,
  depth: number,
  height: number,
  color: number,
  options: Pick<
    WorldObject,
    "accentColor" | "collidable" | "lidarVisible" | "pattern" | "yaw"
  > = {},
): WorldObject {
  return {
    id,
    kind,
    position: { x, y },
    size: { x: width, y: depth },
    height,
    color,
    ...options,
  };
}

function light(
  id: string,
  x: number,
  y: number,
  color = 0xffd8a8,
  intensity = 5.5,
  distance = 5.5,
  fixture: LightFixtureKind = "pendant",
  height = 2.2,
): WorldLight {
  return { id, position: { x, y }, height, color, intensity, distance, fixture };
}

